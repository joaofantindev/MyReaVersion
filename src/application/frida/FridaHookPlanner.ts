import { createHash } from "node:crypto";

import type {
  FridaHookPlan,
  PlanFridaHooksInput,
} from "../../domain/fridaHookPlan.js";

const sha256 = (value: string): string =>
  createHash("sha256").update(value, "utf8").digest("hex");

const scriptLimitations = [
  "This plan is inert text. It observes only functions exported by the selected module or by the global namespace and does not prove that any hook ran.",
  "Targets are resolved once when the script loads. A module or export that is not present at that moment is reported as missing and is not retried.",
  "String reads are bounded and return null when the pointer is null, unreadable, or lacks a terminator inside the selected byte limit.",
  "Raw pointer and return values are addresses. Their meaning depends on the target ABI, calling convention, and the selected function.",
  "The generated script never changes arguments, return values, registers, memory, or control flow. Argument mutation and anti-debug or anti-VM bypass are out of scope.",
  "Frida 17 module and export APIs are required. Older Module.findExportByName or Module.getExportByName forms are not emitted.",
  "Generated JavaScript is not analyzed by REA. Review it before loading it into a caller-selected process.",
] as const;

const renderScript = (targets: FridaHookPlan["targets"]): string => {
  const encodedTargets = JSON.stringify(
    targets.map((target) => ({
      id: target.id,
      module: target.module,
      symbol: target.symbol,
      argument_count: target.argument_count,
      read_string_arguments: target.read_string_arguments,
      max_string_bytes: target.max_string_bytes,
      include_return_value: target.include_return_value,
      include_backtrace: target.include_backtrace,
      backtrace_depth: target.backtrace_depth,
    })),
    null,
    2,
  );
  return `/* Generated by REA plan_frida_hooks. Observation only. */
"use strict";

const TARGETS = ${encodedTargets};

function resolveTarget(target) {
  try {
    if (target.module === null)
      return Module.findGlobalExportByName(target.symbol);
    const module = Process.findModuleByName(target.module);
    if (module === null) return null;
    return module.findExportByName(target.symbol);
  } catch (error) {
    return null;
  }
}

function boundedText(value, maximum) {
  if (value === null || value.isNull()) return null;
  try {
    return value.readUtf8String(maximum);
  } catch (error) {
    return null;
  }
}

function boundedBacktrace(context, depth) {
  try {
    return Thread.backtrace(context, Backtracer.ACCURATE)
      .slice(0, depth)
      .map(function (address) {
        try {
          return DebugSymbol.fromAddress(address).toString();
        } catch (error) {
          return address.toString();
        }
      });
  } catch (error) {
    return [];
  }
}

function emit(event, target, fields) {
  const message = {
    rea_hook_plan: 1,
    event: event,
    target_id: target.id,
    module: target.module,
    symbol: target.symbol
  };
  for (const key of Object.keys(fields)) message[key] = fields[key];
  send(message);
}

const attached = [];
const missing = [];

for (const target of TARGETS) {
  const address = resolveTarget(target);
  if (address === null) {
    missing.push({
      target_id: target.id,
      module: target.module,
      symbol: target.symbol
    });
    continue;
  }
  try {
    Interceptor.attach(address, {
      onEnter: function (args) {
        const rows = [];
        for (let index = 0; index < target.argument_count; index++) {
          const value = args[index];
          const row = { index: index, pointer: value.toString() };
          if (target.read_string_arguments.indexOf(index) !== -1)
            row.string = boundedText(value, target.max_string_bytes);
          rows.push(row);
        }
        const fields = { arguments: rows };
        if (target.include_backtrace)
          fields.backtrace = boundedBacktrace(this.context, target.backtrace_depth);
        emit("enter", target, fields);
      },
      onLeave: function (retval) {
        if (target.include_return_value)
          emit("leave", target, { return_value: retval.toString() });
      }
    });
    attached.push(target.id);
  } catch (error) {
    missing.push({
      target_id: target.id,
      module: target.module,
      symbol: target.symbol
    });
  }
}

send({ rea_hook_plan: 1, event: "ready", attached: attached, missing: missing });
`;
};

/** Build an observation-only Frida 17 hook script without attaching or running it. */
export const planFridaHooks = (input: PlanFridaHooksInput): FridaHookPlan => {
  const targets: FridaHookPlan["targets"] = input.targets.map(
    (target, index) => ({
      id: `hook_${String(index + 1)}`,
      module: target.module ?? null,
      symbol: target.symbol,
      argument_count: target.argument_count,
      read_string_arguments: target.read_string_arguments,
      max_string_bytes: target.max_string_bytes,
      include_return_value: target.include_return_value,
      include_backtrace: target.include_backtrace,
      backtrace_depth: target.backtrace_depth,
    }),
  );
  const script = renderScript(targets);
  return {
    plan_version: 1,
    targets,
    script,
    script_sha256: sha256(script),
    script_bytes: Buffer.byteLength(script, "utf8"),
    runtime: {
      frida_major: 17,
      target_resolution: "global-export-or-module-instance",
    },
    limitations: [...scriptLimitations],
  };
};
