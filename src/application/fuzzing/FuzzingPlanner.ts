import { createHash } from "node:crypto";

import type {
  FuzzingPlan,
  PlanFuzzingCampaignInput,
} from "../../domain/native/fuzzingPlan.js";
import { pythonLiteral as pythonValue } from "../pythonLiteral.js";

const sha256 = (value: string): string =>
  createHash("sha256").update(value, "utf8").digest("hex");

const scriptLimitations = [
  "This plan is inert text. REA did not execute AFL++, Python, or the fuzz target and does not prove that any crash will be discovered.",
  "The generated script reads the original target and stops when its SHA-256 differs from the planned artifact. A replacement after that check is not prevented.",
  "AFL++ and the selected target are caller-supplied. REA does not install, pin, configure, or verify either one.",
  "The target is executed by the generated script. Run it only in an isolated environment with the authorization and resource controls required for that target.",
  "The campaign writes queues, crash inputs, and hang inputs under output_directory. Existing directory contents are retained and may be reused by AFL++.",
  "Crash and hang files are candidate inputs, not crash reports. Use inspect_recorded_crash only on a supplied core file and inspect_apple_ips only on a supplied Apple .ips report.",
  "Coverage, crash uniqueness, exploitation potential, and the validity of any recovered input remain unknown until the generated script runs and the resulting artifacts are examined.",
  "Target arguments and dictionary contents are caller-supplied. The plan rejects NUL bytes and more than one exact @@ substitution, but does not validate target behavior.",
  "This workflow does not perform autonomous exploit generation, taint analysis, anti-debug or anti-VM bypass, or integrity-check evasion.",
] as const;

const renderScript = (
  input: PlanFuzzingCampaignInput,
  artifact: FuzzingPlan["artifact"],
): string => `#!/usr/bin/env python3
"""Generated by REA plan_fuzzing_campaign as inert text.

Review the selected target, directories, arguments, and limits before running
this script with a caller-supplied AFL++ installation. REA did not execute it.
"""
import hashlib
import json
import os
import shlex
import subprocess
import time

TARGET_PATH = ${pythonValue(artifact.path)}
TARGET_SHA256 = ${pythonValue(artifact.sha256)}
CORPUS_DIRECTORY = ${pythonValue(input.corpus_directory)}
OUTPUT_DIRECTORY = ${pythonValue(input.output_directory)}
DICTIONARY_PATH = ${pythonValue(input.dictionary_path ?? null)}
TARGET_ARGUMENTS = ${pythonValue(input.target_arguments)}
MAX_RUNTIME_SECONDS = ${input.max_runtime_seconds.toString()}
TIMEOUT_MS = ${input.timeout_ms.toString()}
MEMORY_LIMIT_MB = ${input.memory_limit_mb.toString()}
MAX_ARTIFACTS = 64


def report(payload):
    print(json.dumps(payload, sort_keys=True))


def file_sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def list_artifacts(directory):
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return []
    kept = []
    for name in names:
        if name.startswith(".") or name == "README.txt":
            continue
        path = os.path.join(directory, name)
        try:
            size = os.path.getsize(path)
        except OSError:
            size = None
        kept.append({"name": name, "path": path, "bytes": size})
        if len(kept) >= MAX_ARTIFACTS:
            break
    return kept


def main():
    try:
        command = shlex.split(
            os.environ.get("REA_AFL_FUZZ_COMMAND", "afl-fuzz").strip()
        )
    except Exception as error:
        report({"status": "error", "stage": "command", "detail": str(error)})
        return 1
    if not command:
        report(
            {
                "status": "error",
                "stage": "command",
                "detail": "REA_AFL_FUZZ_COMMAND is empty.",
            }
        )
        return 1
    if not os.path.isdir(CORPUS_DIRECTORY):
        report(
            {
                "status": "error",
                "stage": "corpus",
                "detail": "Corpus directory does not exist or is not a directory.",
                "path": CORPUS_DIRECTORY,
            }
        )
        return 1

    try:
        observed_sha256 = file_sha256(TARGET_PATH)
    except Exception as error:
        report({"status": "error", "stage": "hash", "detail": str(error)})
        return 1
    if observed_sha256 != TARGET_SHA256:
        report(
            {
                "status": "error",
                "stage": "identity",
                "expected_sha256": TARGET_SHA256,
                "observed_sha256": observed_sha256,
            }
        )
        return 1

    try:
        os.makedirs(OUTPUT_DIRECTORY, exist_ok=True)
    except Exception as error:
        report({"status": "error", "stage": "output", "detail": str(error)})
        return 1

    arguments = [
        *command,
        "-i",
        CORPUS_DIRECTORY,
        "-o",
        OUTPUT_DIRECTORY,
        "-t",
        str(TIMEOUT_MS),
        "-V",
        str(MAX_RUNTIME_SECONDS),
        "-m",
        str(MEMORY_LIMIT_MB),
    ]
    if DICTIONARY_PATH is not None:
        arguments.extend(["-x", DICTIONARY_PATH])
    arguments.extend(["--", TARGET_PATH, *TARGET_ARGUMENTS])

    environment = dict(os.environ)
    environment["AFL_SKIP_CPUFREQ"] = "1"
    environment["AFL_NO_UI"] = "1"
    started = time.monotonic()
    try:
        completed = subprocess.run(
            arguments,
            env=environment,
            capture_output=True,
            timeout=MAX_RUNTIME_SECONDS + 60,
            check=False,
        )
    except subprocess.TimeoutExpired:
        report(
            {
                "status": "timeout",
                "stage": "campaign",
                "elapsed_seconds": round(time.monotonic() - started, 3),
                "artifact_sha256": TARGET_SHA256,
                "output_directory": OUTPUT_DIRECTORY,
                "crashes": list_artifacts(
                    os.path.join(OUTPUT_DIRECTORY, "default", "crashes")
                ),
                "hangs": list_artifacts(
                    os.path.join(OUTPUT_DIRECTORY, "default", "hangs")
                ),
            }
        )
        return 0
    except Exception as error:
        report({"status": "error", "stage": "campaign", "detail": str(error)})
        return 1

    report(
        {
            "status": "complete",
            "stage": "campaign",
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "artifact_sha256": TARGET_SHA256,
            "command": arguments,
            "exit_code": completed.returncode,
            "stdout_bytes": len(completed.stdout),
            "stderr_bytes": len(completed.stderr),
            "stderr": completed.stderr[:65536].decode(
                "utf-8", errors="replace"
            ),
            "output_directory": OUTPUT_DIRECTORY,
            "crashes": list_artifacts(
                os.path.join(OUTPUT_DIRECTORY, "default", "crashes")
            ),
            "hangs": list_artifacts(
                os.path.join(OUTPUT_DIRECTORY, "default", "hangs")
            ),
        }
    )
    return 0 if completed.returncode == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
`;

/** Build an inert AFL++ campaign plan for a caller-selected target identity. */
export const planFuzzingCampaign = (
  input: PlanFuzzingCampaignInput,
  artifact: FuzzingPlan["artifact"],
): FuzzingPlan => {
  const script = renderScript(input, artifact);
  return {
    plan_version: 1,
    artifact,
    runtime: {
      python: "3",
      engine: "afl++",
      command_environment: "REA_AFL_FUZZ_COMMAND",
      target_arguments: input.target_arguments,
    },
    campaign: {
      corpus_directory: input.corpus_directory,
      output_directory: input.output_directory,
      dictionary_path: input.dictionary_path ?? null,
    },
    limits: {
      max_runtime_seconds: input.max_runtime_seconds,
      timeout_ms: input.timeout_ms,
      memory_limit_mb: input.memory_limit_mb,
    },
    script,
    script_sha256: sha256(script),
    script_bytes: Buffer.byteLength(script, "utf8"),
    limitations: [...scriptLimitations],
  };
};
