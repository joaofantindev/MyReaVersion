import { createHash } from "node:crypto";

import type {
  MemoryForensicsPlan,
  PlanMemoryForensicsInput,
} from "../../domain/native/memoryForensicsPlan.js";
import { pythonLiteral as pythonValue } from "../pythonLiteral.js";

const sha256 = (value: string): string =>
  createHash("sha256").update(value, "utf8").digest("hex");

const scriptLimitations = [
  "This plan is inert text. REA did not execute Volatility, Python, or the selected memory image and does not prove that any plugin will succeed.",
  "The generated script reads the original path and stops when its SHA-256 differs from the planned artifact. A replacement after that check is not prevented.",
  "Volatility 3, its symbol tables, and the command named by REA_VOLATILITY_COMMAND are caller-supplied. REA does not install, pin, or verify that installation.",
  "Only plugin names selected in this plan are passed as argument-vector entries. The plan does not accept arbitrary plugin arguments or shell fragments.",
  "Each plugin runs with a bounded deadline and retained output budget. A timed-out or oversized plugin reports a bounded error and later plugins continue.",
  "Volatility plugin output depends on image completeness, operating-system version, symbol availability, and memory layout. Missing symbols or unsupported versions are reported by the tool, not inferred by REA.",
  "Recovered process, network, credential, and string records are observations from the image. Their freshness, validity, and relation to a live system remain unknown.",
  "Repeating a plugin name does not merge results. Duplicate selections are rejected before planning.",
  "This workflow does not acquire live memory, execute the captured target, perform taint analysis, generate exploits, or bypass anti-debug or anti-VM checks.",
] as const;

const renderScript = (
  input: PlanMemoryForensicsInput,
  artifact: MemoryForensicsPlan["artifact"],
): string => `#!/usr/bin/env python3
"""Generated by REA plan_memory_forensics as inert text.

Review the selected image, plugin list, and resource limits before running this
script with a caller-supplied Volatility 3 installation. REA did not execute it.
"""
import hashlib
import json
import os
import shlex
import subprocess
import time

IMAGE_PATH = ${pythonValue(artifact.path)}
TARGET_SHA256 = ${pythonValue(artifact.sha256)}
PLUGINS = ${pythonValue(input.plugins)}
TIMEOUT_SECONDS = ${input.timeout_seconds.toString()}
MAX_OUTPUT_BYTES = ${input.max_output_bytes.toString()}
MAX_RECORDS = 512


def report(payload):
    print(json.dumps(payload, sort_keys=True))


def file_sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def parse_records(text):
    try:
        value = json.loads(text)
    except Exception:
        value = None
    if isinstance(value, list):
        return value
    if isinstance(value, dict):
        return [value]
    records = []
    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            records.append(json.loads(line))
        except Exception:
            continue
    return records


def run_plugin(command, plugin):
    started = time.monotonic()
    try:
        completed = subprocess.run(
            [*command, "-r", "json", "-f", IMAGE_PATH, plugin],
            capture_output=True,
            timeout=TIMEOUT_SECONDS,
            check=False,
        )
    except subprocess.TimeoutExpired:
        return {
            "plugin": plugin,
            "status": "timeout",
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "exit_code": None,
            "records": [],
            "records_truncated": False,
            "stdout_bytes": 0,
            "stderr_bytes": 0,
            "stderr": "",
        }
    except Exception as error:
        return {
            "plugin": plugin,
            "status": "error",
            "elapsed_seconds": round(time.monotonic() - started, 3),
            "exit_code": None,
            "records": [],
            "records_truncated": False,
            "stdout_bytes": 0,
            "stderr_bytes": 0,
            "stderr": str(error),
        }

    stdout = completed.stdout[:MAX_OUTPUT_BYTES]
    stderr = completed.stderr[:MAX_OUTPUT_BYTES]
    records = parse_records(stdout.decode("utf-8", errors="replace"))
    return {
        "plugin": plugin,
        "status": "ok" if completed.returncode == 0 else "failed",
        "elapsed_seconds": round(time.monotonic() - started, 3),
        "exit_code": completed.returncode,
        "records": records[:MAX_RECORDS],
        "records_truncated": len(records) > MAX_RECORDS,
        "stdout_bytes": len(completed.stdout),
        "stderr_bytes": len(completed.stderr),
        "stderr": stderr.decode("utf-8", errors="replace"),
    }


def main():
    try:
        command = shlex.split(
            os.environ.get("REA_VOLATILITY_COMMAND", "vol").strip()
        )
    except Exception as error:
        report({"status": "error", "stage": "command", "detail": str(error)})
        return 1
    if not command:
        report(
            {
                "status": "error",
                "stage": "command",
                "detail": "REA_VOLATILITY_COMMAND is empty.",
            }
        )
        return 1

    try:
        observed_sha256 = file_sha256(IMAGE_PATH)
    except Exception as error:
        report({"status": "error", "stage": "hash", "detail": str(error)})
        return 1
    if observed_sha256 != TARGET_SHA256:
        report(
            {
                "status": "error",
                "stage": "identity",
                "expected_sha256": TARGET_SHA256,
                "observed_sha256": observed_sha256,
            }
        )
        return 1

    results = [run_plugin(command, plugin) for plugin in PLUGINS]
    report(
        {
            "status": "complete",
            "artifact_sha256": TARGET_SHA256,
            "command": command,
            "plugins": results,
        }
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
`;

/** Build an inert Volatility 3 plan for a caller-selected memory image. */
export const planMemoryForensics = (
  input: PlanMemoryForensicsInput,
  artifact: MemoryForensicsPlan["artifact"],
): MemoryForensicsPlan => {
  const script = renderScript(input, artifact);
  return {
    plan_version: 1,
    artifact,
    runtime: {
      python: "3",
      engine: "volatility3",
      renderer: "json",
      command_environment: "REA_VOLATILITY_COMMAND",
      plugins: input.plugins.map((name) => ({
        name,
        argument_vector: ["-r", "json", "-f", artifact.path, name],
      })),
    },
    limits: {
      timeout_seconds: input.timeout_seconds,
      max_output_bytes: input.max_output_bytes,
    },
    script,
    script_sha256: sha256(script),
    script_bytes: Buffer.byteLength(script, "utf8"),
    limitations: [...scriptLimitations],
  };
};
