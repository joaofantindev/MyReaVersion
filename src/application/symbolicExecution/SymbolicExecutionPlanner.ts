import { createHash } from "node:crypto";

import type {
  PlanSymbolicExecutionInput,
  SymbolicExecutionPlan,
  SymbolicTarget,
} from "../../domain/native/symbolicExecutionPlan.js";
import { pythonLiteral as pythonValue } from "../pythonLiteral.js";

const sha256 = (value: string): string =>
  createHash("sha256").update(value, "utf8").digest("hex");

const scriptLimitations = [
  "This plan is inert text. REA did not execute angr or the selected binary and does not prove that any target path exists.",
  "The generated script reads the original path and stops when its SHA-256 differs from the planned artifact. A replacement after that check is not prevented.",
  "Symbols resolve through the caller's angr loader. A missing symbol, unsupported container, or loader failure stops the script with a JSON error.",
  "auto_load_libs is disabled, so external library calls and simulated dependencies are not loaded. Their behavior can differ from a native run.",
  "entry_state models the selected entry with angr defaults. Environment variables, files, the working directory, and stdin are not symbolized or reproduced.",
  "Only positional argv entries selected by symbolic_arguments are symbolic. Each has a fixed byte length, and other inputs remain concrete.",
  "The generated script stops at max_steps or deadline_seconds and reports the reached status. A stopped or exhausted search does not prove a find target is unreachable.",
  "Solution bytes come from the first found state and may not satisfy caller intent beyond the declared find and avoid targets. They are not a working payload or a stable exploit.",
  "Python, angr, solver, and loader behavior are caller-supplied and not verified by REA. The plan records no angr version pin.",
] as const;

const renderTarget = (target: SymbolicTarget | null): string =>
  pythonValue(target);

const renderScript = (
  input: PlanSymbolicExecutionInput,
  artifact: SymbolicExecutionPlan["artifact"],
): string => `#!/usr/bin/env python3
"""Generated by REA plan_symbolic_execution as inert text.

Review target selection, declared targets, and resource limits before running
this script with a caller-supplied angr installation. REA did not execute it.
"""
import hashlib
import json
import time

import angr
import claripy

PROJECT_PATH = ${pythonValue(artifact.path)}
TARGET_SHA256 = ${pythonValue(artifact.sha256)}
ENTRY = ${renderTarget(input.entry ?? null)}
FIND = ${pythonValue(input.find)}
AVOID = ${pythonValue(input.avoid)}
MAX_STEPS = ${input.max_steps.toString()}
DEADLINE_SECONDS = ${input.deadline_seconds.toString()}
SYMBOLIC_ARGUMENTS = ${input.symbolic_arguments.toString()}
MAX_ARGUMENT_BYTES = ${input.max_symbolic_argument_bytes.toString()}
MAX_SOLUTION_BYTES = ${input.max_solution_bytes.toString()}


def report(payload):
    print(json.dumps(payload, sort_keys=True))


def file_sha256(path):
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def resolve(project, target):
    if target["kind"] == "address":
        return int(target["value"], 16)
    symbol = project.loader.find_symbol(target["value"])
    if symbol is None:
        return None
    return symbol.rebased_addr


def resolve_all(project, targets, role):
    resolved = []
    for target in targets:
        address = resolve(project, target)
        if address is None:
            report({"status": "error", "stage": role, "target": target})
            return None
        resolved.append(address)
    return resolved


def main():
    started = time.monotonic()
    try:
        observed_sha256 = file_sha256(PROJECT_PATH)
    except Exception as error:
        report({"status": "error", "stage": "hash", "detail": str(error)})
        return 1
    if observed_sha256 != TARGET_SHA256:
        report(
            {
                "status": "error",
                "stage": "identity",
                "expected_sha256": TARGET_SHA256,
                "observed_sha256": observed_sha256,
            }
        )
        return 1

    try:
        project = angr.Project(PROJECT_PATH, auto_load_libs=False)
    except Exception as error:
        report({"status": "error", "stage": "project", "detail": str(error)})
        return 1

    find = resolve_all(project, FIND, "find")
    if find is None:
        return 1
    avoid = resolve_all(project, AVOID, "avoid")
    if avoid is None:
        return 1

    symbols = []
    arguments = None
    if SYMBOLIC_ARGUMENTS > 0:
        arguments = [project.filename]
        for index in range(SYMBOLIC_ARGUMENTS):
            name = "rea_argv_%d" % index
            symbol = claripy.BVS(name, 8 * MAX_ARGUMENT_BYTES)
            symbols.append((name, symbol))
            arguments.append(symbol)

    try:
        if ENTRY is None:
            state = project.factory.entry_state(args=arguments)
        else:
            entry = resolve(project, ENTRY)
            if entry is None:
                report({"status": "error", "stage": "entry", "target": ENTRY})
                return 1
            state = project.factory.entry_state(addr=entry, args=arguments)
    except Exception as error:
        report({"status": "error", "stage": "state", "detail": str(error)})
        return 1

    try:
        simgr = project.factory.simulation_manager(
            state, find=find, avoid=avoid
        )
    except Exception as error:
        report({"status": "error", "stage": "manager", "detail": str(error)})
        return 1
    steps = 0
    status = "exhausted"
    while not simgr.found and simgr.active:
        if steps >= MAX_STEPS:
            status = "step-limit"
            break
        if time.monotonic() - started >= DEADLINE_SECONDS:
            status = "deadline"
            break
        simgr.step()
        steps += 1
    if simgr.found:
        status = "found"

    result = {
        "status": status,
        "steps": steps,
        "elapsed_seconds": round(time.monotonic() - started, 3),
        "artifact_sha256": TARGET_SHA256,
        "counts": {
            "found": len(simgr.found),
            "active": len(simgr.active),
            "deadended": len(simgr.deadended),
            "errored": len(simgr.errored),
        },
        "find": [target["value"] for target in FIND],
        "avoid": [target["value"] for target in AVOID],
        "solutions": [],
    }

    if simgr.found:
        found = simgr.found[0]
        result["found_address"] = hex(found.addr)
        for name, symbol in symbols:
            try:
                value = found.solver.eval(symbol, cast_to=bytes)
            except Exception as error:
                result["solutions"].append({"name": name, "error": str(error)})
                continue
            kept = value[:MAX_SOLUTION_BYTES]
            result["solutions"].append(
                {
                    "name": name,
                    "bytes": len(value),
                    "truncated": len(value) > MAX_SOLUTION_BYTES,
                    "hex": kept.hex(),
                }
            )

    report(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
`;

/** Build an inert angr plan for a caller-selected artifact identity. */
export const planSymbolicExecution = (
  input: PlanSymbolicExecutionInput,
  artifact: SymbolicExecutionPlan["artifact"],
): SymbolicExecutionPlan => {
  const script = renderScript(input, artifact);
  return {
    plan_version: 1,
    artifact,
    runtime: {
      python: "3",
      engine: "angr",
      api: "project-simulation-manager",
      shared_libraries: "disabled",
    },
    entry: input.entry ?? null,
    find: input.find,
    avoid: input.avoid,
    limits: {
      max_steps: input.max_steps,
      deadline_seconds: input.deadline_seconds,
      symbolic_arguments: input.symbolic_arguments,
      max_symbolic_argument_bytes: input.max_symbolic_argument_bytes,
      max_solution_bytes: input.max_solution_bytes,
    },
    script,
    script_sha256: sha256(script),
    script_bytes: Buffer.byteLength(script, "utf8"),
    limitations: [...scriptLimitations],
  };
};
